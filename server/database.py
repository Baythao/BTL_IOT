"""Shared SQLite/PostgreSQL interface. Set DATABASE_URL for PostgreSQL."""
import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path

ROOT = Path(__file__).resolve().parent

class HybridRow:
    def __init__(self, values, names):
        self.values = tuple(values)
        self.mapping = dict(zip(names, values))
    def __getitem__(self, key):
        return self.values[key] if isinstance(key, int) else self.mapping[key]
    def keys(self):
        return self.mapping.keys()
    def __iter__(self):
        return iter(self.values)

class PgCursor:
    def __init__(self, cur):
        self.cur = cur
        self.rowcount = cur.rowcount
        self.lastrowid = None
    def fetchone(self):
        item = self.cur.fetchone()
        return HybridRow(item, [c.name for c in self.cur.description]) if item is not None else None
    def fetchall(self):
        names = [c.name for c in self.cur.description]
        return [HybridRow(r, names) for r in self.cur.fetchall()]
    def __iter__(self):
        names = [c.name for c in self.cur.description]
        for row in self.cur:
            yield HybridRow(row, names)

class PgConnection:
    def __init__(self, conn):
        self.conn = conn
    def execute(self, sql, args=()):
        statement = sql.strip()
        if statement.upper() == 'BEGIN IMMEDIATE':
            return PgCursor(self.conn.execute('SELECT 1'))
        if statement.upper().startswith('PRAGMA '):
            return PgCursor(self.conn.execute('SELECT 1'))
        sql = re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql, flags=re.I)
        sql = re.sub(r'INSERT OR IGNORE INTO (\w+) VALUES \(\?,\?,\?\)', r'INSERT INTO \1 VALUES (?,?,?) ON CONFLICT DO NOTHING', sql, flags=re.I)
        if 'INSERT INTO users(username,full_name,password_hash,role,permissions,active,must_change,created)' in sql or 'INSERT INTO users(username,full_name,password_hash,role,permissions,created)' in sql:
            sql += ' RETURNING id'
        sql = sql.replace('?', '%s')
        cur = self.conn.execute(sql, args)
        wrapped = PgCursor(cur)
        if 'RETURNING id' in sql:
            row = cur.fetchone()
            wrapped.lastrowid = row[0] if row else None
        return wrapped

@contextmanager
def database(path=None):
    url = os.getenv('DATABASE_URL', '').strip()
    if url:
        if not url.startswith(('postgresql://', 'postgres://')):
            raise ValueError('DATABASE_URL must start with postgresql://')
        import psycopg
        with psycopg.connect(url, connect_timeout=10) as conn:
            yield PgConnection(conn)
    else:
        db = sqlite3.connect(str(path or ROOT / 'alerts.sqlite3'), timeout=15)
        db.row_factory = sqlite3.Row
        db.execute('PRAGMA journal_mode=WAL')
        try:
            with db:
                yield db
        finally:
            db.close()

def integrity_error():
    if os.getenv('DATABASE_URL', '').strip():
        from psycopg import errors
        return (sqlite3.IntegrityError, errors.UniqueViolation)
    return (sqlite3.IntegrityError,)
